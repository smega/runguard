package main

import (
	"context"
	"fmt"
	"log"
	"net/http"
	"time"

	"github.com/gin-gonic/gin"
	"go.mongodb.org/mongo-driver/bson"
	"go.mongodb.org/mongo-driver/bson/primitive"
)

// handleRegenerateJobKey replaces a job's heartbeat key, for when the old
// one leaked (a log, a screenshot, a public repo). The job keeps its
// history, settings and public page; only the /hb/<key> URL changes, and
// the old URL stops working immediately, so whatever pings it has to be
// switched to the new one.
func (a *App) handleRegenerateJobKey(c *gin.Context) {
	u, ok := currentUser(c)
	if !ok {
		c.JSON(http.StatusUnauthorized, gin.H{"error": "unauthorized"})
		return
	}

	jobID, err := primitive.ObjectIDFromHex(c.Param("id"))
	if err != nil {
		c.JSON(http.StatusBadRequest, gin.H{"error": "invalid job id"})
		return
	}

	ctx, cancel := context.WithTimeout(c.Request.Context(), 10*time.Second)
	defer cancel()

	var job Job
	if err := a.jobsColl.FindOne(ctx, bson.M{
		"_id":        jobID,
		"user_id":    u.ID,
		"deleted_at": bson.M{"$exists": false},
	}).Decode(&job); err != nil {
		c.JSON(http.StatusNotFound, gin.H{"error": "job not found"})
		return
	}

	token, err := generateTokenString(16)
	if err != nil {
		log.Printf("generate job key for %s: %v", job.ID.Hex(), err)
		c.JSON(http.StatusInternalServerError, gin.H{"error": "internal error"})
		return
	}
	key := fmt.Sprintf("rg_%s_%s", token, heartbeatKeySlug(job.Name))

	if _, err := a.jobsColl.UpdateByID(ctx, job.ID, bson.M{"$set": bson.M{
		"key":        key,
		"updated_at": time.Now().UTC(),
	}}); err != nil {
		log.Printf("regenerate job key for %s: %v", job.ID.Hex(), err)
		c.JSON(http.StatusInternalServerError, gin.H{"error": "db error"})
		return
	}
	log.Printf("job %s: heartbeat key regenerated by user %s", job.ID.Hex(), u.ID.Hex())

	c.JSON(http.StatusOK, gin.H{
		"heartbeat_url": fmt.Sprintf("%s/hb/%s", a.cfg.PublicBaseURL, key),
	})
}
